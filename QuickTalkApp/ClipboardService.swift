import AppKit
import Combine

/// 클립보드 감시자 — `changeCount` 폴링(0.7s)으로 최근 항목을 모은다(PLAN_v0.12).
/// - 만료 2분 · 최대 5개 (`ClipboardPolicy`)
/// - 클립보드는 **읽기만** 한다. 내용은 로그·캡처에 남기지 않는다([HARD] 로그 마스킹).
/// - 타이머는 메인 런루프에서 돌므로 상태 변경은 항상 메인 스레드에서 일어난다.
final class ClipboardService: ObservableObject {
  static let pollInterval: TimeInterval = 0.7

  @Published private(set) var items: [ClipboardItem] = []
  /// 민감 항목 공개 상태(사용자가 눌러서 펼친 것만)
  @Published private(set) var revealedIDs: Set<UUID> = []

  private var ring = ClipboardRing()
  private var timer: Timer?
  private var lastChangeCount = NSPasteboard.general.changeCount

  func start() {
    guard timer == nil else { return }
    lastChangeCount = NSPasteboard.general.changeCount
    // 앱 시작 시점에 이미 복사돼 있는 내용도 올린다 — "복사 → 바로 창 열기" 흐름(방금 복사 = 2분 유지)
    if let item = read(from: NSPasteboard.general) {
      ring.insert(item)
      NSLog("[QuickTalk] 클립보드 시작 시 수집 kind=%@ sensitive=%@", item.kind.rawValue,
            item.isSensitive ? "Y" : "N")
    }
    items = ring.items
    let t = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
      self?.poll()
    }
    t.tolerance = 0.3
    timer = t
    NSLog("[QuickTalk] 클립보드 감시 시작 (ttl=%.0fs, max=%d)",
          ClipboardPolicy.ttl, ClipboardPolicy.maxItems)
  }

  func stop() {
    timer?.invalidate()
    timer = nil
  }

  func remove(_ id: UUID) {
    ring.remove(id)
    revealedIDs.remove(id)
    items = ring.items
  }

  func clear() {
    ring.removeAll()
    revealedIDs.removeAll()
    items = ring.items
  }

  /// 민감 항목 공개 토글 — 내용은 로그로 내보내지 않는다.
  func reveal(_ id: UUID) {
    if revealedIDs.contains(id) { revealedIDs.remove(id) } else { revealedIDs.insert(id) }
  }

  func isRevealed(_ id: UUID) -> Bool { revealedIDs.contains(id) }

  /// 표시용 텍스트(민감 항목은 공개 전까지 마스킹)
  func displayText(_ item: ClipboardItem) -> String {
    ClipboardPolicy.displayText(item, revealed: revealedIDs.contains(item.id))
  }

  func secondsLeft(_ item: ClipboardItem, now: Date = Date()) -> Int {
    ClipboardPolicy.secondsLeft(item, now: now)
  }

  // MARK: - 내부

  private func poll() {
    let expired = ring.expire()
    if expired > 0 {
      // 개수만 남긴다 — 어떤 내용이었는지는 기록하지 않는다
      NSLog("[QuickTalk] 클립보드 만료 정리 %d건 (남음 %d)", expired, ring.items.count)
    }
    let pb = NSPasteboard.general
    guard pb.changeCount != lastChangeCount else { syncIfNeeded(); return }
    lastChangeCount = pb.changeCount
    guard let item = read(from: pb) else { syncIfNeeded(); return }
    ring.insert(item)
    NSLog("[QuickTalk] 클립보드 항목 추가 kind=%@ sensitive=%@ 개수=%d",
          item.kind.rawValue, item.isSensitive ? "Y" : "N", ring.items.count)
    syncIfNeeded(force: true)
  }

  /// 링이 바뀐 경우에만 퍼블리시(만료 카운트다운으로 인한 불필요한 리렌더 방지)
  private func syncIfNeeded(force: Bool = false) {
    if force || items != ring.items { items = ring.items }
  }

  private func read(from pb: NSPasteboard) -> ClipboardItem? {
    let types = Set(pb.types?.map { $0.rawValue } ?? [])
    // 비밀번호 관리자·드래그 중 항목이 붙이는 표준 마커
    let concealed = types.contains("org.nspasteboard.ConcealedType")
    let transient = types.contains("org.nspasteboard.TransientType")
    let autoGenerated = types.contains("org.nspasteboard.AutoGeneratedType")
    if transient || autoGenerated { return nil }   // 일시적·자동 생성 항목은 수집하지 않는다

    if let text = pb.string(forType: .string), !text.isEmpty {
      let trimmed = String(text.prefix(ClipboardPolicy.maxTextLength))
      let kind: ClipboardItem.Kind = ClipboardPolicy.looksLikeURL(trimmed) ? .link : .text
      return ClipboardItem(kind: kind, text: trimmed,
                           isSensitive: concealed || ClipboardPolicy.looksSensitive(trimmed))
    }

    if types.contains(NSPasteboard.PasteboardType.tiff.rawValue)
        || types.contains(NSPasteboard.PasteboardType.png.rawValue),
       let image = NSImage(pasteboard: pb), let data = thumbnailPNG(image) {
      return ClipboardItem(kind: .image, text: Lf("이미지 %d×%d", Int(image.size.width), Int(image.size.height)),
                           imageData: data, isSensitive: concealed)
    }

    if let urls = pb.readObjects(forClasses: [NSURL.self]) as? [URL], let first = urls.first {
      // 파일 URL을 보관한다 — 버리면 첨부할 때 본문을 읽을 수 없다(P1)
      return ClipboardItem(kind: .file, text: first.lastPathComponent,
                           isSensitive: concealed, fileURL: first)
    }

    return nil
  }

  /// 썸네일용 축소 PNG — 원본을 그대로 들고 있지 않는다.
  private func thumbnailPNG(_ image: NSImage) -> Data? {
    let size = image.size
    guard size.width > 0, size.height > 0 else { return nil }
    let maxSide = CGFloat(ClipboardPolicy.thumbnailMaxSide)
    let scale = min(1, maxSide / max(size.width, size.height))
    let target = NSSize(width: max(1, (size.width * scale).rounded()),
                        height: max(1, (size.height * scale).rounded()))
    let thumb = NSImage(size: target)
    thumb.lockFocus()
    NSGraphicsContext.current?.imageInterpolation = .high
    image.draw(in: NSRect(origin: .zero, size: target),
               from: NSRect(origin: .zero, size: size), operation: .copy, fraction: 1)
    thumb.unlockFocus()
    guard let tiff = thumb.tiffRepresentation,
          let rep = NSBitmapImageRep(data: tiff) else { return nil }
    return rep.representation(using: .png, properties: [:])
  }
}
